var termByName = func() map[string]Term {
	m := map[string]Term{}
	for _, t := range Terms {
		m[t.Name] = t
	}
	return m
}()

// termID はテンプレートから用語名で ID を引く。未知の名前はエラー（テンプレート実行が止まる）。
func termID(name string) (string, error) {
	t, ok := termByName[name]
	if !ok {
		return "", fmt.Errorf("用語 %q は Terms にありません", name)
	}
	return t.ID, nil
}

type termsData struct {
	Terms []Term
}

// writeTerms は用語の説明ページを書く。
func writeTerms(w io.Writer) error {
	return templates.ExecuteTemplate(w, "terms.html", termsData{Terms: Terms})
}
